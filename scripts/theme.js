const themes = [
    "Dark", "Terminal", "Evening", "Royal", "Twilight", "Maroon",
    "Light", "Sepia"
];
let current_i = 0;

window.nextTheme = function () {
    current_i = (current_i + 1) % themes.length;
    window.theme = themes[current_i];

    let toggleTo;
    switch (window.theme) {
        case "Dark"     : toggleTo = darkTheme;     break;
        case "Terminal" : toggleTo = terminalTheme; break;
        case "Evening"  : toggleTo = eveningTheme;  break;
        case "Royal"    : toggleTo = royalTheme;    break;
        case "Twilight" : toggleTo = twilightTheme; break;
        case "Maroon"   : toggleTo = maroonTheme;   break;
        case "Light"    : toggleTo = lightTheme;    break;
        case "Sepia"    : toggleTo = sepiaTheme;    break;
    }

    for (const [key, value] of Object.entries(toggleTo)) {
        document.documentElement.style.setProperty(key, value);
    }
};
